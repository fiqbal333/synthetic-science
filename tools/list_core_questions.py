"""List the core research questions and theory families of the Stage 1 worlds, with each seed's hidden true effect.

Usage: python tools/list_core_questions.py [out.md] [out.csv]
Reads runs/S0-150/{1,2,3}/llm/landscape/{questions,families,truth}.json (the repository world at the same seed shares the
landscape). Reports whether the question set (id, constructs, variables, prediction) is identical across seeds, and which
fields differ.
"""
import csv
import json
import sys
from pathlib import Path

W = Path(__file__).resolve().parents[1]
SEEDS = (1, 2, 3)
KEYS = ("id", "family", "iv", "iv_label", "iv_var", "dv", "dv_label", "dv_var", "moderators", "prediction", "design", "core")


def load(seed):
    d = W / "runs" / "S0-150" / str(seed) / "llm" / "landscape"
    q = json.loads((d / "questions.json").read_text(encoding="utf-8"))
    t = json.loads((d / "truth.json").read_text(encoding="utf-8"))
    f = json.loads((d / "families.json").read_text(encoding="utf-8"))
    return [x for x in q if x.get("core", True)], t, f


def sign(prediction: str) -> str:
    # the predicted direction is the verb of the claim before "because" (e.g. "... higher X lowers Y, because ...")
    claim = prediction.lower().split("because")[0]
    if any(w in claim for w in (" lowers ", " reduces ", " decreases ", " weakens ")):
        return "-"
    if any(w in claim for w in (" raises ", " increases ", " strengthens ", " improves ")):
        return "+"
    return "?"


def main(out_md=None, out_csv=None):
    runs = {s: load(s) for s in SEEDS}
    fams = runs[1][2]
    base = {q["id"]: q for q in runs[1][0]}
    same, diff_fields = True, set()
    for s in SEEDS[1:]:
        other = {q["id"]: q for q in runs[s][0]}
        if set(other) != set(base):
            same = False
        for qid, q in base.items():
            o = other.get(qid)
            if o is None:
                continue
            for k in set(q) | set(o):
                if q.get(k) != o.get(k):
                    (diff_fields.add(k))
                    if k in KEYS:
                        same = False
    rows = []
    for qid in sorted(base, key=lambda i: (base[i]["family"], i)):
        q = base[qid]
        tr = [runs[s][1]["questions"].get(qid, {}) for s in SEEDS]
        rows.append({
            "family": fams[q["family"]]["label"], "id": qid, "independent": q.get("iv_label", q["iv"]),
            "dependent": q.get("dv_label", q["dv"]), "predicted_sign": {"positive": "+", "negative": "-"}.get(q.get("prediction_sign"), sign(q.get("prediction", ""))),
            "moderators": ", ".join(q.get("moderators", [])), "design": q.get("design", ""),
            "corpus_papers": q.get("corpus_papers", ""),
            **{f"true_r_s{s}": (round(t.get("theta"), 3) if isinstance(t.get("theta"), (int, float)) else "") for s, t in zip(SEEDS, tr)},
            **{f"truth_s{s}": t.get("truth_class", "") for s, t in zip(SEEDS, tr)},
            "prediction": q.get("prediction", ""),
        })
    n_fam = {}
    for r in rows:
        n_fam[r["family"]] = n_fam.get(r["family"], 0) + 1
    lines = ["# Core research questions of the Stage 1 worlds", "",
             f"Generated by `tools/list_core_questions.py` from `runs/S0-150/{{1,2,3}}/llm/landscape/` (the repository world at each seed "
             f"shares its landscape). {len(rows)} core questions in {len(n_fam)} theory families: "
             + "; ".join(f"{k} {v}" for k, v in sorted(n_fam.items())) + ".", "",
             f"The questions themselves (id, theory family, independent and dependent constructs and variables, prediction) are "
             f"**{'identical' if not (diff_fields & {'id', 'family', 'iv', 'iv_label', 'iv_var', 'dv', 'dv_label', 'dv_var', 'prediction'}) else 'NOT identical'}** "
             f"across seeds 1-3. Drawn per seed: {', '.join(sorted(diff_fields)) or 'nothing'} (the moderators, design and data frame "
             f"of each question), plus the hidden true effects. The Moderators and Design columns below are seed 1's.", "",
             "True effect = the hidden correlation-scale effect (theta) drawn for that seed, with its truth class. No agent ever sees it. "
             "Authors see the questions with plain labels; handbook writers see per-seed shuffled construct codes (landscape/deid_map.json).", ""]
    for fam in sorted(n_fam):
        lines += [f"## {fam} ({n_fam[fam]} questions)", "",
                  "| ID | Independent variable | Dependent variable | Predicted | Moderators | SMJ papers | True r (s1 / s2 / s3) | Truth class (s1 / s2 / s3) |",
                  "|---|---|---|---|---|---|---|---|"]
        for r in [r for r in rows if r["family"] == fam]:
            lines.append(f"| {r['id']} | {r['independent']} | {r['dependent']} | {r['predicted_sign']} | {r['moderators']} | {r['corpus_papers']} | "
                         f"{r['true_r_s1']} / {r['true_r_s2']} / {r['true_r_s3']} | {r['truth_s1']} / {r['truth_s2']} / {r['truth_s3']} |")
        lines.append("")
    lines += ["## The prediction each question tests", ""] + [f"- **{r['id']}**: {r['prediction']}" for r in rows]
    text = "\n".join(lines) + "\n"
    if out_md:
        Path(out_md).write_text(text, encoding="utf-8")
    if out_csv:
        with open(out_csv, "w", newline="", encoding="utf-8") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    print(lines[2]); print(lines[4])


if __name__ == "__main__":
    main(*sys.argv[1:])
