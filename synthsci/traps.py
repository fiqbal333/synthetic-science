"""Trap registry. Traps are discoverable only from the data, never from text.

Each trap: applicability (by dataset design), plant(df) -> df, correct(df) -> df (the correct handling the oracle uses),
naive_spec(spec) (how the naive analysis differs), analytic(est, se, rng) (the sufficient-statistics bias for fast mode),
and `handled(...)` (the deterministic oracle for an analyst's output).
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable

import numpy as np
import pandas as pd

MEDIATOR_VAR = "operating_efficiency"
MEDIATOR_SHARE = 0.6   # share of the IV's total effect that flows through the mediator (design default)


@dataclass
class Trap:
    name: str
    applicable: Callable[[dict], bool]
    plant: Callable[[pd.DataFrame, dict, np.random.Generator], pd.DataFrame]
    correct: Callable[[pd.DataFrame, dict], pd.DataFrame]
    naive_controls: Callable[[list[str], dict], list[str]]   # how the naive analysis changes the controls list
    analytic: Callable[[float, float, np.random.Generator, dict], tuple[float, float]]   # (est, se) -> biased (est, se)
    signature: str          # what inspection shows (hidden documentation only)
    handled_codes: tuple    # self-report codes in `sample_changes` that count as handling


# ------------------------------------------------------------------ duplicates
def _plant_dup(df, spec, r):
    share = float(r.uniform(0.03, 0.08))
    k = int(round(share * len(df)))
    dup = df.iloc[r.choice(len(df), k, replace=False)]
    out = pd.concat([df, dup], ignore_index=True)
    return out.iloc[r.permutation(len(out))].reset_index(drop=True)


def _correct_dup(df, spec):
    return df.drop_duplicates().reset_index(drop=True)


def _analytic_dup(est, se, r, spec):
    return est, se * 0.95  # SEs understated; N inflated; estimate unbiased


# ------------------------------------------------------------------ scale mixture
def _plant_scale(df, spec, r):
    df = df.copy()
    dv = spec["dv_var"]
    mask = df["data_source"].to_numpy() == "B"
    df.loc[mask, dv] = np.round(df.loc[mask, dv] * 100.0, 4)
    return df


def _correct_scale(df, spec):
    df = df.copy()
    dv = spec["dv_var"]
    mask = df["data_source"].to_numpy() == "B"
    df.loc[mask, dv] = df.loc[mask, dv] / 100.0
    return df


def _analytic_scale(est, se, r, spec):
    return est * 0.41 + r.normal(0, 0.02), se * 1.3


# ------------------------------------------------------------------ reverse-coded item
def _plant_reverse(df, spec, r):
    df = df.copy()
    iv = spec["iv_var"]
    # deliver the survey IV as three items on 1-7; the third is reverse-scored and NOT reversed in the file
    z = (df[iv] - df[iv].mean()) / (df[iv].std() + 1e-9)
    for i in (1, 2, 3):
        item = np.clip(np.round(4 + 1.2 * z + r.normal(0, 0.9, len(df))), 1, 7)
        if i == 3:
            item = 8 - item
        df[f"{iv}_item{i}"] = item.astype(int)
    return df.drop(columns=[iv])


def _correct_reverse(df, spec):
    df = df.copy()
    iv = spec["iv_var"]
    df[iv] = (df[f"{iv}_item1"] + df[f"{iv}_item2"] + (8 - df[f"{iv}_item3"])) / 3.0
    return df


def _naive_reverse_prepare(df, spec):
    df = df.copy()
    iv = spec["iv_var"]
    df[iv] = (df[f"{iv}_item1"] + df[f"{iv}_item2"] + df[f"{iv}_item3"]) / 3.0
    return df


def _analytic_reverse(est, se, r, spec):
    return est * 0.35, se


# ------------------------------------------------------------------ selection on the outcome
def _plant_selection(df, spec, r):
    dv = spec["dv_var"]
    thr = df[dv].quantile(0.25)
    out = df[df[dv] >= thr].reset_index(drop=True)
    return out


def _correct_selection(df, spec):
    return df  # cannot be undone; handled by acknowledgement


def _analytic_selection(est, se, r, spec):
    return est * 0.7, se * 1.1


# ------------------------------------------------------------------ bad control (mediator in the controls pool)
def _plant_bad(df, spec, r):
    return df  # the mediator column is generated by the DGP when this trap is planted


def _correct_bad(df, spec):
    return df


def _analytic_bad(est, se, r, spec):
    return est * (1.0 - MEDIATOR_SHARE), se


# ------------------------------------------------------------------ mis-coded values
def _plant_miscoded(df, spec, r):
    df = df.copy()
    k = max(3, int(round(0.005 * len(df))))
    idx = r.choice(len(df), k, replace=False)
    iv = spec["iv_var"]
    half = k // 2
    if iv in df.columns:   # a survey IV delivered as items (reverse_coded) has no single column; the two traps are exclusive anyway
        df.loc[df.index[idx[:half]], iv] = 999.0
    if "leverage" in df.columns:
        df.loc[df.index[idx[half:]], "leverage"] = 999.0
    if "firm_age" in df.columns:
        df.loc[df.index[idx[half:]], "firm_age"] = -5.0
    return df


def _correct_miscoded(df, spec):
    df = df.copy()
    iv = spec["iv_var"]
    mask = (df[iv] >= 999.0).to_numpy() if iv in df.columns else np.zeros(len(df), dtype=bool)
    if "leverage" in df.columns:
        mask |= (df["leverage"] >= 999.0).to_numpy()
    if "firm_age" in df.columns:
        mask |= (df["firm_age"] < 0).to_numpy()
    return df[~mask].reset_index(drop=True)


def _analytic_miscoded(est, se, r, spec):
    return est * 0.15 + r.normal(0, 0.01), se * 0.9


# ------------------------------------------------------------------ unit mismatch (one year in other units)
def _plant_unit(df, spec, r):
    df = df.copy()
    years = sorted(df["year"].unique())
    yr = years[int(r.integers(len(years)))]
    dv = spec["dv_var"]
    mask = df["year"].to_numpy() == yr
    df.loc[mask, dv] = np.round(df.loc[mask, dv] * 1000.0, 4)
    return df


def _correct_unit(df, spec):
    df = df.copy()
    dv = spec["dv_var"]
    med = df.groupby("year")[dv].median()
    overall = med.median()
    bad_years = [y for y, m in med.items() if abs(m) > 50 * (abs(overall) + 0.05)]
    for y in bad_years:
        mask = df["year"].to_numpy() == y
        df.loc[mask, dv] = df.loc[mask, dv] / 1000.0
    return df


def _analytic_unit(est, se, r, spec):
    return est * 0.3 + r.normal(0, 0.03), se * 1.5


# ------------------------------------------------------------------ omitted standard control (size matters more than usual)
def _plant_omit(df, spec, r):
    return df  # the DGP raises the size-IV and size-DV correlations when this trap is planted


def _correct_omit(df, spec):
    return df


def _naive_controls_omit(controls, spec):
    return [c for c in controls if c != "ln_assets"]


def _analytic_omit(est, se, r, spec):
    return est + 0.12 * np.sign(est if est != 0 else 1.0) * (1 if r.uniform() < 0.8 else -1), se


def _identity_controls(controls, spec):
    return list(controls)


def _naive_controls_bad(controls, spec):
    return list(controls) + [MEDIATOR_VAR]


REGISTRY: dict[str, Trap] = {
    "duplicates": Trap("duplicates", lambda s: True, _plant_dup, _correct_dup, _identity_controls, _analytic_dup,
                       "duplicated firm-year or firm identifiers", ("deduplicated", "dropped_duplicates", "duplicates_removed")),
    "scale_mixture": Trap("scale_mixture", lambda s: s["dv_kind"] != "binary", _plant_scale, _correct_scale, _identity_controls,
                          _analytic_scale, "bimodal outcome; source-B values about 100x", ("rescaled", "rescaled_source_b", "source_restricted")),
    "reverse_coded": Trap("reverse_coded", lambda s: s["iv_source"] == "survey", _plant_reverse, _correct_reverse,
                          _identity_controls, _analytic_reverse, "negative item-total correlation for item 3",
                          ("item_reversed", "reversed_item", "reverse_scored")),
    "selection_on_outcome": Trap("selection_on_outcome", lambda s: s["dv_kind"] != "binary" and not s["panel"], _plant_selection,
                                 _correct_selection, _identity_controls, _analytic_selection,
                                 "truncated outcome: no observations below the threshold", ("selection_acknowledged", "truncation_acknowledged")),
    "bad_control": Trap("bad_control", lambda s: True, _plant_bad, _correct_bad, _naive_controls_bad, _analytic_bad,
                        f"{MEDIATOR_VAR} is measured at the end of the period and moves with the focal variable",
                        ("excluded_post_treatment_control", "excluded_mediator")),
    "miscoded_values": Trap("miscoded_values", lambda s: True, _plant_miscoded, _correct_miscoded, _identity_controls,
                            _analytic_miscoded, "impossible values (999; negative age)", ("dropped_impossible_values", "range_corrected", "winsorized")),
    "unit_mismatch": Trap("unit_mismatch", lambda s: s["panel"] and s["dv_kind"] != "binary", _plant_unit, _correct_unit,
                          _identity_controls, _analytic_unit, "year-wise discontinuity in the outcome", ("rescaled_year", "unit_corrected")),
    "omitted_standard_control": Trap("omitted_standard_control", lambda s: "ln_assets" in s["controls"], _plant_omit, _correct_omit,
                                     _naive_controls_omit, _analytic_omit, "size strongly correlated with both focal variables", ("size_included",)),
}

PRE_FIT_NAIVE = {"reverse_coded": _naive_reverse_prepare}


def applicable_traps(spec: dict, registry: list[str] | None = None) -> list[str]:
    names = registry or list(REGISTRY)
    return [n for n in names if n in REGISTRY and REGISTRY[n].applicable(spec)]


def draw_traps(spec: dict, r: np.random.Generator, density: dict, registry: list[str] | None = None) -> list[str]:
    """Zero, one or two traps at the configured density (`datasets.traps.density`, a design default)."""
    u = r.uniform()
    if u < density["two"]:
        k = 2
    elif u < density["two"] + density["one"]:
        k = 1
    else:
        k = 0
    pool = applicable_traps(spec, registry)
    if not pool or k == 0:
        return []
    k = min(k, len(pool))
    picks = r.choice(len(pool), k, replace=False)
    chosen = [pool[int(i)] for i in picks]
    if "unit_mismatch" in chosen and "scale_mixture" in chosen:   # two rescalings of the DV are not separable
        chosen.remove("unit_mismatch")
    if "reverse_coded" in chosen and "miscoded_values" in chosen:  # the survey IV is delivered as items; no single column to mis-code
        chosen.remove("miscoded_values")
    return sorted(chosen)


def handled_by_report(trap: str, sample_changes: list) -> bool:
    codes = {str(c).lower() for c in (sample_changes or [])}
    return any(code in codes for code in REGISTRY[trap].handled_codes)
